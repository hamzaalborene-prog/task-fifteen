import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error

# دعم عرض الحروف العربية في الرسومات (اختياري، إذا لم تكن المكتبتان مثبتتين يعمل الكود بدونهما)
try:
    import arabic_reshaper
    from bidi.algorithm import get_display

    def عربي(النص):
        return get_display(arabic_reshaper.reshape(النص))
except ImportError:
    def عربي(النص):
        return النص

# إعدادات عامة للعرض
pd.set_option('display.width', 200)
sns.set_theme(style='whitegrid')


def عنوان(النص):
    # دالة صغيرة لطباعة عنوان واضح لكل جزء
    print()
    print('=' * 70)
    print(النص)
    print('=' * 70)


def احفظ_واعرض(اسم_الملف):
    # نحفظ الرسمة كصورة ثم نعرضها (الحفظ لازم يكون قبل العرض)
    plt.tight_layout()
    plt.savefig(اسم_الملف, dpi=150)
    plt.show()


# =====================================================================
# تحميل داتاسيت tips
# =====================================================================
بيانات_المطعم = sns.load_dataset('tips')
عنوان('نظرة أولية على بيانات tips')
print('عدد الصفوف والأعمدة:', بيانات_المطعم.shape)
print(بيانات_المطعم.head())


# =====================================================================
# الجزء 1: أول نموذج Linear Regression
# =====================================================================

# --- التمرين 1: تقسيم البيانات إلى Train و Test (80/20) ---
عنوان('الجزء 1 - التمرين 1: تقسيم البيانات 80/20')

# X لازم يكون جدول (عمود بين قوسين مزدوجين) و y عمود واحد
س_الفاتورة = بيانات_المطعم[['total_bill']]
ص_الإكرامية = بيانات_المطعم['tip']

# random_state ثابت حتى تطلع نفس النتيجة كل مرة نشغّل فيها الكود
س_تدريب, س_اختبار, ص_تدريب, ص_اختبار = train_test_split(
    س_الفاتورة, ص_الإكرامية, test_size=0.2, random_state=42)
print('عدد صفوف التدريب:', len(س_تدريب), '، عدد صفوف الاختبار:', len(س_اختبار))

# --- التمرين 2: تدريب النموذج (متغير وحيد: total_bill) ---
عنوان('الجزء 1 - التمرين 2: تدريب النموذج')
نموذج_الفاتورة = LinearRegression()
نموذج_الفاتورة.fit(س_تدريب, ص_تدريب)
print('تم تدريب النموذج على بيانات التدريب فقط.')

# --- التمرين 3: أول 10 توقعات مقابل القيم الحقيقية ---
عنوان('الجزء 1 - التمرين 3: أول 10 توقعات مقابل القيم الحقيقية')
التوقعات = نموذج_الفاتورة.predict(س_اختبار)
جدول_المقارنة = pd.DataFrame({
    'الفاتورة': س_اختبار['total_bill'].values,
    'الإكرامية_الحقيقية': ص_اختبار.values,
    'الإكرامية_المتوقعة': التوقعات.round(2),
})
جدول_المقارنة['الفرق'] = (جدول_المقارنة['الإكرامية_الحقيقية'] - جدول_المقارنة['الإكرامية_المتوقعة']).round(2)
print(جدول_المقارنة.head(10))

# --- التمرين 4: حساب R² على بيانات الاختبار ---
عنوان('الجزء 1 - التمرين 4: R² على بيانات الاختبار')
ر_تربيع_الفاتورة = نموذج_الفاتورة.score(س_اختبار, ص_اختبار)
print(f'R² لنموذج total_bill = {ر_تربيع_الفاتورة:.3f}')
print(f'التفسير: النموذج يفسّر حوالي {ر_تربيع_الفاتورة * 100:.0f}% من التغيّر في قيمة الإكرامية اعتماداً على قيمة الفاتورة فقط،')
print(f'والباقي (حوالي {(1 - ر_تربيع_الفاتورة) * 100:.0f}%) سببه عوامل أخرى لا يعرفها النموذج (جودة الخدمة، كرم الزبون...).')


# =====================================================================
# الجزء 2: تفسير المعاملات بلغة بزنس
# =====================================================================

# --- التمرين 1: طباعة الميل والمقطع ---
عنوان('الجزء 2 - التمرين 1: الميل والمقطع')
الميل_الفاتورة = نموذج_الفاتورة.coef_[0]
المقطع_الفاتورة = نموذج_الفاتورة.intercept_
print(f'الميل (coef_) = {الميل_الفاتورة:.4f}')
print(f'المقطع (intercept_) = {المقطع_الفاتورة:.4f}')
print(f'المعادلة: الإكرامية = {الميل_الفاتورة:.4f} × الفاتورة + {المقطع_الفاتورة:.4f}')

# --- التمرين 2: تفسير الميل بلغة بزنس ---
عنوان('الجزء 2 - التمرين 2: تفسير الميل بلغة بزنس')
print(f'كل ما زادت قيمة الفاتورة بدولار واحد، الإكرامية المتوقعة بتزيد بمقدار {الميل_الفاتورة:.3f} دولار.')
print(f'(يعني كل 10 دولار زيادة بالفاتورة تقريباً {الميل_الفاتورة * 10:.2f} دولار زيادة بالإكرامية.)')
print(f'والمقطع {المقطع_الفاتورة:.2f} هو الإكرامية المتوقعة نظرياً لفاتورة صفر، ولا معنى عملي له بحد ذاته.')

# رسمة توضح الخط مع نقاط الاختبار
plt.figure(figsize=(8, 5))
plt.scatter(س_اختبار['total_bill'], ص_اختبار, color='steelblue', label=عربي('القيم الحقيقية (اختبار)'))
ترتيب = س_اختبار['total_bill'].argsort()
plt.plot(س_اختبار['total_bill'].values[ترتيب], التوقعات[ترتيب], color='red', label=عربي('خط الانحدار'))
plt.title(عربي('الإكرامية مقابل قيمة الفاتورة مع خط الانحدار'))
plt.xlabel(عربي('قيمة الفاتورة'))
plt.ylabel(عربي('الإكرامية'))
plt.legend()
احفظ_واعرض('رسمة_1_خط_الانحدار_الفاتورة.png')

# --- التمرين 3: نموذج ثاني بالمتغير size ومقارنة R² ---
عنوان('الجزء 2 - التمرين 3: نموذج size ومقارنة R²')
س_الحجم = بيانات_المطعم[['size']]
# نفس random_state ونفس حجم البيانات = نفس الصفوف في التدريب والاختبار، فالمقارنة عادلة
س_حجم_تدريب, س_حجم_اختبار, ص_حجم_تدريب, ص_حجم_اختبار = train_test_split(
    س_الحجم, ص_الإكرامية, test_size=0.2, random_state=42)

نموذج_الحجم = LinearRegression()
نموذج_الحجم.fit(س_حجم_تدريب, ص_حجم_تدريب)
ر_تربيع_الحجم = نموذج_الحجم.score(س_حجم_اختبار, ص_حجم_اختبار)
الميل_الحجم = نموذج_الحجم.coef_[0]

print(f'نموذج size: الميل = {الميل_الحجم:.3f} ، المقطع = {نموذج_الحجم.intercept_:.3f}')
print(f'R² لنموذج total_bill = {ر_تربيع_الفاتورة:.3f}')
print(f'R² لنموذج size       = {ر_تربيع_الحجم:.3f}')
if ر_تربيع_الفاتورة > ر_تربيع_الحجم:
    print('الأقوى: total_bill هو المؤشر الأقوى على قيمة الإكرامية لأن R² الخاص به أعلى.')
else:
    print('الأقوى: size هو المؤشر الأقوى على قيمة الإكرامية لأن R² الخاص به أعلى.')
print(f'تفسير ميل size: كل شخص إضافي على الطاولة يزيد الإكرامية المتوقعة بحوالي {الميل_الحجم:.2f} دولار.')

# --- التمرين 4: فقرة لمدير المطعم ---
عنوان('الجزء 2 - التمرين 4: جواب مدير المطعم')
print(f'''سؤال المدير: هل الطاولات الكبيرة بتترك إكرامية أعلى بشكل مضمون؟
الجواب: بشكل عام نعم الاتجاه موجب، فكل شخص إضافي على الطاولة يرافقه زيادة متوقعة بحوالي {الميل_الحجم:.2f} دولار بالإكرامية.
لكن R² لنموذج حجم الطاولة فقط {ر_تربيع_الحجم:.2f}، أي أن عدد الأشخاص يفسّر حوالي {ر_تربيع_الحجم * 100:.0f}% فقط من اختلاف الإكراميات،
فالعلاقة موجودة لكنها ضعيفة ولا يمكن اعتبارها مضمونة.
لذلك لا أنصح بالاعتماد على حجم الطاولة لوحده في قرار مهم (مثل تحديد الأجور أو توزيع الطاقم)، وقيمة الفاتورة مؤشر أفضل منه.''')


# =====================================================================
# الجزء 3: Regression لتوقع اتجاه بسيط (بيانات flights)
# =====================================================================
عنوان('الجزء 3 - التمرين 1: تحميل بيانات flights وتلخيصها شهرياً')
بيانات_الطيران = sns.load_dataset('flights')
print(بيانات_الطيران.head())

# نبني عمود تاريخ من السنة واسم الشهر
بيانات_الطيران['التاريخ'] = pd.to_datetime(
    بيانات_الطيران['year'].astype(str) + '-' + بيانات_الطيران['month'].astype(str), format='%Y-%b')

# تلخيص شهري: نجمع الركاب لكل شهر (البيانات أصلاً شهرية فالنتيجة نفسها، لكن هذه هي الخطوة المطلوبة)
ركاب_شهرياً = بيانات_الطيران.groupby('التاريخ')['passengers'].sum().reset_index()
ركاب_شهرياً = ركاب_شهرياً.sort_values('التاريخ').reset_index(drop=True)
print('عدد الأشهر:', len(ركاب_شهرياً))
print(ركاب_شهرياً.head())

# --- التمرين 2: تحويل التاريخ لرقم متسلسل ---
عنوان('الجزء 3 - التمرين 2: رقم الشهر المتسلسل')
ركاب_شهرياً['رقم_الشهر'] = range(1, len(ركاب_شهرياً) + 1)
print(ركاب_شهرياً[['التاريخ', 'رقم_الشهر', 'passengers']].head())
print(ركاب_شهرياً[['التاريخ', 'رقم_الشهر', 'passengers']].tail())

# --- التمرين 3: تدريب النموذج ---
عنوان('الجزء 3 - التمرين 3: تدريب نموذج الاتجاه')
س_الأشهر = ركاب_شهرياً[['رقم_الشهر']]
ص_الركاب = ركاب_شهرياً['passengers']

نموذج_الاتجاه = LinearRegression()
نموذج_الاتجاه.fit(س_الأشهر, ص_الركاب)
ر_تربيع_الاتجاه = نموذج_الاتجاه.score(س_الأشهر, ص_الركاب)
print(f'الميل = {نموذج_الاتجاه.coef_[0]:.2f} ، المقطع = {نموذج_الاتجاه.intercept_:.2f} ، R² = {ر_تربيع_الاتجاه:.3f}')
print(f'التفسير: عدد الركاب يزداد في المتوسط بحوالي {نموذج_الاتجاه.coef_[0]:.1f} ألف راكب كل شهر.')

# --- التمرين 4: توقع 6 أشهر إضافية ---
عنوان('الجزء 3 - التمرين 4: توقع 6 أشهر قادمة')
آخر_رقم = ركاب_شهرياً['رقم_الشهر'].max()
أرقام_جديدة = pd.DataFrame({'رقم_الشهر': range(آخر_رقم + 1, آخر_رقم + 7)})
تواريخ_جديدة = pd.date_range(ركاب_شهرياً['التاريخ'].max() + pd.DateOffset(months=1), periods=6, freq='MS')
توقع_الانحدار = نموذج_الاتجاه.predict(أرقام_جديدة)
جدول_التوقع = pd.DataFrame({'التاريخ': تواريخ_جديدة, 'رقم_الشهر': أرقام_جديدة['رقم_الشهر'], 'توقع_الانحدار': توقع_الانحدار.round(1)})
print(جدول_التوقع)

# --- التمرين 5: الرسمة (البيانات + خط الاتجاه + التوقعات) ---
عنوان('الجزء 3 - التمرين 5: الرسمة')
خط_الاتجاه = نموذج_الاتجاه.predict(س_الأشهر)

plt.figure(figsize=(11, 5))
plt.plot(ركاب_شهرياً['التاريخ'], ص_الركاب, color='blue', label=عربي('البيانات الأصلية'))
plt.plot(ركاب_شهرياً['التاريخ'], خط_الاتجاه, color='green', linestyle='--', label=عربي('خط الاتجاه (Trend Line)'))
plt.plot(تواريخ_جديدة, توقع_الانحدار, color='red', marker='o', label=عربي('التوقعات الستة الجديدة'))
plt.title(عربي('عدد الركاب شهرياً مع خط الاتجاه وتوقع 6 أشهر'))
plt.xlabel(عربي('التاريخ'))
plt.ylabel(عربي('عدد الركاب (بالآلاف)'))
plt.legend()
احفظ_واعرض('رسمة_2_الاتجاه_والتوقع.png')

# --- التمرين 6: المقارنة مع Moving Average و Seasonal Naive ---
عنوان('الجزء 3 - التمرين 6: مقارنة الانحدار مع Moving Average و Seasonal Naive')
# (لم يصلني كود تاسك 12، فأعدت بناء الطريقتين بشكل بسيط)

# طريقة Moving Average: متوسط آخر 3 أشهر، ونكرره كتوقع ثابت
توقع_المتوسط_المتحرك = [ص_الركاب.tail(3).mean()] * 6
# طريقة Seasonal Naive: توقع كل شهر = قيمة نفس الشهر قبل سنة
توقع_الموسمي = ص_الركاب.tail(12).head(6).values

مقارنة_التوقعات = pd.DataFrame({
    'التاريخ': تواريخ_جديدة,
    'الانحدار': توقع_الانحدار.round(1),
    'المتوسط_المتحرك': np.round(توقع_المتوسط_المتحرك, 1),
    'Seasonal_Naive': توقع_الموسمي,
})
print(مقارنة_التوقعات)

plt.figure(figsize=(11, 5))
آخر_36 = ركاب_شهرياً.tail(36)
plt.plot(آخر_36['التاريخ'], آخر_36['passengers'], color='blue', label=عربي('آخر 36 شهراً (حقيقي)'))
plt.plot(تواريخ_جديدة, توقع_الانحدار, color='red', marker='o', label=عربي('توقع الانحدار'))
plt.plot(تواريخ_جديدة, توقع_المتوسط_المتحرك, color='orange', marker='s', label=عربي('توقع المتوسط المتحرك'))
plt.plot(تواريخ_جديدة, توقع_الموسمي, color='purple', marker='^', label=عربي('توقع Seasonal Naive'))
plt.title(عربي('مقارنة طرق التوقع للأشهر الستة القادمة'))
plt.xlabel(عربي('التاريخ'))
plt.ylabel(عربي('عدد الركاب (بالآلاف)'))
plt.legend()
احفظ_واعرض('رسمة_3_مقارنة_طرق_التوقع.png')

# بما أن الأشهر الستة القادمة غير معروفة، نختبر الطرق الثلاث على آخر 12 شهراً عندنا (نخفيها ثم نتوقعها)
عدد_التدريب = len(ركاب_شهرياً) - 12
تدريب_زمني = ص_الركاب.iloc[:عدد_التدريب]
اختبار_زمني = ص_الركاب.iloc[عدد_التدريب:]

نموذج_مؤقت = LinearRegression()
نموذج_مؤقت.fit(ركاب_شهرياً[['رقم_الشهر']].iloc[:عدد_التدريب], تدريب_زمني)
توقع_أ = نموذج_مؤقت.predict(ركاب_شهرياً[['رقم_الشهر']].iloc[عدد_التدريب:])
توقع_ب = [تدريب_زمني.tail(3).mean()] * 12
توقع_ج = تدريب_زمني.tail(12).values

خطأ_الانحدار = mean_absolute_error(اختبار_زمني, توقع_أ)
خطأ_المتحرك = mean_absolute_error(اختبار_زمني, توقع_ب)
خطأ_الموسمي = mean_absolute_error(اختبار_زمني, توقع_ج)
print()
print('متوسط الخطأ المطلق (MAE) على آخر 12 شهراً (كلما قل كان أفضل):')
print(f'الانحدار الخطي = {خطأ_الانحدار:.1f} ألف راكب')
print(f'المتوسط المتحرك = {خطأ_المتحرك:.1f} ألف راكب')
print(f'Seasonal Naive = {خطأ_الموسمي:.1f} ألف راكب')

print(f'''
المقارنة والتفسير:
خط الانحدار يلتقط الاتجاه العام الصاعد (R² = {ر_تربيع_الاتجاه:.2f}) لكنه خط مستقيم فلا يعرف أن الصيف أعلى من الشتاء،
لذلك توقعاته الستة تسير بخط صاعد هادئ ولا تتبع شكل المواسم.
المتوسط المتحرك يعطي رقماً ثابتاً تقريباً لكل الأشهر، فلا يلتقط الاتجاه ولا الموسمية، وهو أضعف ما عندنا هنا.
أما Seasonal Naive فيكرر نمط السنة السابقة فيلتقط الموسمية، لكنه لا يلتقط نمو الاتجاه.
بما أن بيانات flights فيها اتجاه صاعد قوي وموسمية قوية معاً، فكل طريقة تلتقط جزءاً واحداً فقط،
والأفضل عملياً دمج الاثنين (الاتجاه من الانحدار + الموسمية من Seasonal Naive).
الطريقة الأقرب بالأرقام على الاختبار: {min([('الانحدار', خطأ_الانحدار), ('المتوسط المتحرك', خطأ_المتحرك), ('Seasonal Naive', خطأ_الموسمي)], key=lambda t: t[1])[0]}.''')

print()
print('تم حفظ الرسومات كصور PNG في نفس المجلد.')
