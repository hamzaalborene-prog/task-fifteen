import os
import glob
import sqlite3
import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LinearRegression

try:
    import arabic_reshaper
    from bidi.algorithm import get_display

    def عربي(النص):
        return get_display(arabic_reshaper.reshape(النص))
except ImportError:
    def عربي(النص):
        return النص

pd.set_option('display.width', 200)
sns.set_theme(style='whitegrid')


def عنوان(النص):
    print()
    print('=' * 70)
    print(النص)
    print('=' * 70)


def احفظ_واعرض(اسم_الملف):
    plt.tight_layout()
    plt.savefig(اسم_الملف, dpi=150)
    plt.show()


# =====================================================================
# سؤال البزنس
# =====================================================================
عنوان('سؤال البزنس')
print('هل إعطاء خصم أكبر على المنتج يجعل الزبائن يشترون كمية أكبر؟')
print('(إذا كان الجواب نعم فالخصومات تستحق تكلفتها، وإذا لا فنحن نخسر جزءاً من الربح بلا فائدة.)')

# =====================================================================
# تحميل البيانات من ملف قاعدة البيانات
# =====================================================================
# الملف نصي فيه أوامر SQL، نشغّله داخل قاعدة بيانات مؤقتة في الذاكرة
# نبحث عن الملف في نفس مجلد هذا الكود (حتى لو شغّلنا الكود من VS Code من مجلد آخر)
مجلد_الكود = os.path.dirname(os.path.abspath(__file__))
# نأخذ أي ملف اسمه يبدأ بـ store_db_dump (حتى لو تغيّر الاسم عند التحميل، مثل store_db_dump__1_.txt)
الملفات_الموجودة = glob.glob(os.path.join(مجلد_الكود, 'store_db_dump*.txt'))
if len(الملفات_الموجودة) == 0:
    print('لم أجد ملف الداتا بيس في المجلد:', مجلد_الكود)
    print('ضع الملف store_db_dump (1).txt بجانب هذا الكود ثم شغّل مرة أخرى.')
    raise SystemExit
اسم_ملف_القاعدة = الملفات_الموجودة[0]
print('تم استخدام الملف:', اسم_ملف_القاعدة)
اتصال = sqlite3.connect(':memory:')
with open(اسم_ملف_القاعدة, 'r', encoding='utf-8') as ملف:
    اتصال.executescript(ملف.read())

# ندمج جدول المبيعات مع جدول المنتجات لنحصل على سعر المنتج
بيانات_المبيعات = pd.read_sql_query('''
    SELECT s.sale_id, s.quantity, s.discount, p.price, p.category
    FROM sales s
    JOIN products p ON s.product_id = p.product_id
''', اتصال)
اتصال.close()

عنوان('نظرة أولية على البيانات')
print('عدد الصفوف والأعمدة:', بيانات_المبيعات.shape)
print(بيانات_المبيعات.head())
print('القيم الفارغة:')
print(بيانات_المبيعات.isnull().sum())
print(بيانات_المبيعات[['quantity', 'discount', 'price']].describe().round(2))

# =====================================================================
# تنظيف القيم الشاذة في الكمية (طريقة IQR)
# =====================================================================
عنوان('تنظيف القيم الشاذة في quantity')
ربيع1 = بيانات_المبيعات['quantity'].quantile(0.25)
ربيع3 = بيانات_المبيعات['quantity'].quantile(0.75)
مدى = ربيع3 - ربيع1
الحد_الأعلى = ربيع3 + 1.5 * مدى
print(f'الحد الأعلى للكمية الطبيعية = {الحد_الأعلى:.1f}')

الصفوف_الشاذة = بيانات_المبيعات[بيانات_المبيعات['quantity'] > الحد_الأعلى]
print(f'عدد العمليات ذات الكمية الشاذة = {len(الصفوف_الشاذة)}')
print('أكبر 5 كميات:')
print(بيانات_المبيعات.nlargest(5, 'quantity')[['sale_id', 'quantity', 'discount', 'price']])

# نحذف الشاذ (طلبات بالجملة مثل 250 قطعة) لأنها لا تمثل الشراء العادي وتشوّه الخط
بيانات_نظيفة = بيانات_المبيعات[بيانات_المبيعات['quantity'] <= الحد_الأعلى].copy()
print(f'بعد التنظيف بقي {len(بيانات_نظيفة)} صفاً من أصل {len(بيانات_المبيعات)}')

# =====================================================================
# استكشاف سريع بالأرقام والرسم
# =====================================================================
عنوان('متوسط الكمية لكل مستوى خصم')
متوسط_حسب_الخصم = بيانات_نظيفة.groupby('discount')['quantity'].agg(['mean', 'count']).round(2)
print(متوسط_حسب_الخصم)

plt.figure(figsize=(8, 5))
sns.barplot(data=بيانات_نظيفة, x='discount', y='quantity', errorbar=None, color='steelblue')
plt.title(عربي('متوسط الكمية المباعة حسب نسبة الخصم'))
plt.xlabel(عربي('نسبة الخصم'))
plt.ylabel(عربي('متوسط الكمية'))
احفظ_واعرض('مشروع_رسمة_1_الكمية_حسب_الخصم.png')

# =====================================================================
# النموذج الأول: الكمية حسب الخصم فقط
# =====================================================================
عنوان('النموذج الأول: الكمية حسب الخصم فقط')
ص_الكمية = بيانات_نظيفة['quantity']
س_خصم = بيانات_نظيفة[['discount']]
س_خصم_تدريب, س_خصم_اختبار, ص_تدريب, ص_اختبار = train_test_split(
    س_خصم, ص_الكمية, test_size=0.2, random_state=42)

نموذج_الخصم = LinearRegression()
نموذج_الخصم.fit(س_خصم_تدريب, ص_تدريب)
ر_تربيع_الخصم = نموذج_الخصم.score(س_خصم_اختبار, ص_اختبار)
ميل_الخصم = نموذج_الخصم.coef_[0]

print(f'الميل = {ميل_الخصم:.3f} ، المقطع = {نموذج_الخصم.intercept_:.3f} ، R² (اختبار) = {ر_تربيع_الخصم:.4f}')
print(f'الخصم يتراوح بين 0 و 0.15، فرفع الخصم 10 نقاط مئوية (مثلاً من 0% إلى 10%) يغيّر الكمية المتوقعة بمقدار {ميل_الخصم * 0.10:.2f} قطعة.')

# =====================================================================
# النموذج الثاني: الخصم + سعر المنتج
# =====================================================================
عنوان('النموذج الثاني: الخصم + سعر المنتج')
س_اثنين = بيانات_نظيفة[['discount', 'price']]
س_اثنين_تدريب, س_اثنين_اختبار, ص_تدريب2, ص_اختبار2 = train_test_split(
    س_اثنين, ص_الكمية, test_size=0.2, random_state=42)

نموذج_اثنين = LinearRegression()
نموذج_اثنين.fit(س_اثنين_تدريب, ص_تدريب2)
ر_تربيع_اثنين = نموذج_اثنين.score(س_اثنين_اختبار, ص_اختبار2)
ميل_الخصم2 = نموذج_اثنين.coef_[0]
ميل_السعر = نموذج_اثنين.coef_[1]

print(f'ميل الخصم = {ميل_الخصم2:.3f} ، ميل السعر = {ميل_السعر:.4f} ، المقطع = {نموذج_اثنين.intercept_:.3f}')
print(f'R² (اختبار) = {ر_تربيع_اثنين:.4f}')

# نموذج للسعر وحده لنعرف أي المتغيرين هو الأقوى
س_سعر = بيانات_نظيفة[['price']]
س_سعر_تدريب, س_سعر_اختبار, ص_تدريب3, ص_اختبار3 = train_test_split(
    س_سعر, ص_الكمية, test_size=0.2, random_state=42)
نموذج_السعر = LinearRegression()
نموذج_السعر.fit(س_سعر_تدريب, ص_تدريب3)
ر_تربيع_السعر = نموذج_السعر.score(س_سعر_اختبار, ص_اختبار3)
print(f'R² لنموذج السعر وحده = {ر_تربيع_السعر:.4f}')

# =====================================================================
# تفسير المعاملات بلغة بزنس
# =====================================================================
عنوان('تفسير المعاملات بلغة بزنس')
print(f'1) الخصم: عند ثبات السعر، رفع الخصم 10 نقاط مئوية يغيّر الكمية المباعة بمقدار {ميل_الخصم2 * 0.10:.2f} قطعة لكل عملية بيع، وهذا رقم صغير جداً.')
print(f'2) السعر: كل دولار زيادة بسعر المنتج يغيّر الكمية المتوقعة بمقدار {ميل_السعر:.3f} قطعة (الإشارة السالبة تعني أن المنتجات الأغلى تُباع بكميات أقل).')

# =====================================================================
# تقييم قوة العلاقة
# =====================================================================
عنوان('تقييم قوة العلاقة (R²)')
print(f'R² للخصم وحده     = {ر_تربيع_الخصم:.4f}')
print(f'R² للسعر وحده      = {ر_تربيع_السعر:.4f}')
print(f'R² للخصم + السعر   = {ر_تربيع_اثنين:.4f}')
print(f'''
القراءة: الخصم يفسّر تقريباً {max(ر_تربيع_الخصم, 0) * 100:.1f}% فقط من اختلاف الكمية، أي أنه عملياً لا يتنبأ بالكمية.
السعر مؤشر أقوى بوضوح (R² = {ر_تربيع_السعر:.3f}) لكنه أيضاً يفسّر جزءاً صغيراً فقط ولا يكفي لوحده لاتخاذ قرار.
الخلاصة: العلاقة بين الخصم والكمية ضعيفة جداً وغير كافية للاعتماد عليها في قرار تسعير.
(ملاحظة: R² السالب أو القريب من الصفر على بيانات الاختبار يعني أن النموذج ليس أفضل من التنبؤ بالمتوسط دائماً.)
(ملاحظة أخرى: هذا مبني على ارتباط ولا يثبت السببية.)''')

# رسمة الانتشار مع خط الانحدار للخصم
plt.figure(figsize=(8, 5))
sns.stripplot(data=بيانات_نظيفة, x='discount', y='quantity', alpha=0.3, color='gray')
plt.title(عربي('الكمية مقابل نسبة الخصم (كل نقطة عملية بيع)'))
plt.xlabel(عربي('نسبة الخصم'))
plt.ylabel(عربي('الكمية'))
احفظ_واعرض('مشروع_رسمة_2_انتشار_الكمية_والخصم.png')

# =====================================================================
# التقرير القصير (فقرتان)
# =====================================================================
عنوان('التقرير النهائي')
التقرير = f'''
تقرير: هل الخصومات تزيد الكميات المباعة؟
-------------------------------------------------------------
الفقرة الأولى (العلاقة المكتشفة): حلّلنا {len(بيانات_نظيفة)} عملية بيع بعد حذف {len(الصفوف_الشاذة)} طلبات بالجملة شاذة.
نموذج الانحدار أظهر أن رفع الخصم 10 نقاط مئوية يغيّر الكمية بمقدار {ميل_الخصم * 0.10:.2f} قطعة فقط لكل عملية بيع،
وأن R² للخصم = {ر_تربيع_الخصم:.3f}، أي أن الخصم لا يفسّر تقريباً شيئاً من اختلاف الكميات.
أما سعر المنتج فمؤشره أقوى (R² = {ر_تربيع_السعر:.3f}) وعلاقته سالبة: كلما ارتفع السعر قلّت الكمية، لكنه أيضاً لا يكفي للاعتماد عليه لوحده.

الفقرة الثانية (التوصية): لا توجد في هذه البيانات أدلة على أن الخصم يزيد الكمية، لذلك أنصح بعدم توسيع الخصومات
أو رفعها بناءً على هذه النتائج، وبمراجعة الخصومات الحالية لأنها قد تقلل الربح بلا مقابل واضح.
وأنصح بتجربة عملية (مثل خصم على منتج محدد لمدة أسبوعين مقابل منتج مشابه بلا خصم) قبل أي قرار نهائي،
مع الانتباه أن النتيجة تعتمد على بيانات 2026 فقط وأن الارتباط لا يثبت السببية.
'''
print(التقرير)

with open('تقرير_المشروع.txt', 'w', encoding='utf-8') as ملف:
    ملف.write(التقرير)
print('تم حفظ التقرير في الملف تقرير_المشروع.txt وحفظ الرسومات كصور PNG.')